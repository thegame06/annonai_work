import type { StoredNode } from '../store/store.ts';

/**
 * One template, four filenames. Divergent per-vendor instructions would
 * reintroduce the vendor coupling the architecture exists to avoid (REQ-0002).
 */
export const AGENT_FILES: readonly { file: string; preamble: string }[] = [
  { file: 'CLAUDE.md', preamble: 'Instructions for Claude Code in this repository.' },
  { file: 'AGENTS.md', preamble: 'Instructions for AI coding agents in this repository.' },
  { file: 'CODEX.md', preamble: 'Instructions for OpenAI Codex CLI in this repository.' },
  { file: 'GEMINI.md', preamble: 'Instructions for Gemini CLI in this repository.' },
];

/**
 * The workflow lives here, not in new commands: the agent orchestrates the CLI
 * and MCP surface that already exist. A test asserts that every command and tool
 * named below is implemented, so the agent is never told to run something absent.
 */
export const renderInstructions = (
  projectName: string,
  preamble: string,
  rules: readonly StoredNode[],
  terms: readonly StoredNode[],
  components: readonly StoredNode[],
): string => {
  const lines = [
    `<!-- GENERATED BY annona compile. Do not edit: changes are lost on the next compile. -->`,
    ``,
    `# ${projectName}`,
    ``,
    `${preamble}`,
    ``,
    `You own the engineering conversation. Annona owns the engineering knowledge.`,
    `The developer thinks about software; you think about Annona. Never ask them to run`,
    `an Annona command, and never make them repeat which task is active.`,
    ``,
    `Questions are expensive. Interruptions are defects. Infer before you ask.`,
    ``,
    `## The loop`,
    ``,
    `\`\`\``,
    `discovery -> brief -> knowledge -> plan -> implement -> review -> done`,
    `                                    ^                     |`,
    `                                    +---------------------+`,
    `\`\`\``,
    ``,
    `You hold the session: active task, assumptions, plan, review history. It lives in`,
    `this conversation, not on disk.`,
    ``,
    `## 0. Know your environment`,
    ``,
    `Before anything else, take stock of what this environment actually gives you.`,
    `You already know your own tools: use that knowledge.`,
    ``,
    `Annona is always present, because it generated this file. Everything else is`,
    `contingent. Check before you reach for it.`,
    ``,
    `**Never announce that something is missing.** Do not say "I need code search" or`,
    `"this would be easier with history". Ask instead what knowledge you need and which`,
    `of your available tools can supply it. An absent integration is never a blocker,`,
    `never an excuse, and never worth mentioning to the developer.`,
    ``,
    `The workflow below is identical whether you have Annona alone or Annona plus a`,
    `dozen other sources. More sources make discovery richer. They never make it`,
    `different.`,
    ``,
    `## 1. Discovery`,
    ``,
    `Discovery is not a checklist of tools. It is building the best engineering`,
    `understanding available to you, in four steps:`,
    ``,
    `**Search.** Cast wide across whatever you can reach.`,
    ``,
    `**Infer.** Most of what you need is deducible. Deduce it.`,
    ``,
    `**Correlate.** Cross-check what different sources tell you. Where they disagree,`,
    `that disagreement is itself a finding worth reporting.`,
    ``,
    `**Ask.** Only what remains genuinely unknown.`,
    ``,
    `The kinds of knowledge worth gathering, in priority order:`,
    ``,
    `1. **Engineering intent** — why this exists, what governs it, what was decided.`,
    `   Annona answers this: \`annona list feature\`, \`annona list component\`,`,
    `   \`annona list rule\`, \`annona get <id>\`.`,
    `2. **Structure** — what exists in the codebase and how it connects.`,
    `3. **History** — how this was solved before, what changed recently, what precedent`,
    `   exists.`,
    `4. **Tracked work** — related items, prior discussion, acceptance criteria.`,
    `5. **Documentation** — anything written down outside the code.`,
    ``,
    `Levels 2 to 5 depend entirely on what your environment exposes. Use what is there.`,
    `Work without what is not. Never name a source you have not confirmed you can use.`,
    ``,
    `## 2. The interview`,
    ``,
    `Ask only what survives all five filters:`,
    ``,
    `1. no available source can answer it`,
    `2. it cannot be inferred from what you already gathered`,
    `3. it cannot be correlated from two partial answers`,
    `4. the answer changes an engineering decision`,
    `5. it reduces implementation uncertainty`,
    ``,
    `**Maximum five questions. Fewer is better.** Adapt them to this project; the`,
    `components listed below tell you what it is. Directions worth at most one question`,
    `each, only when they apply:`,
    ``,
    `- which component owns this, and whether another participates`,
    `- new interface or a change to an existing one`,
    `- produces or consumes events`,
    `- schema change or migration`,
    `- background, scheduled or worker processing`,
    `- cache invalidation`,
    `- aggregate, domain event or invariant`,
    `- authentication, authorization, permissions`,
    ``,
    `Never ask a generic question. Asking about something already recorded tells the`,
    `developer you did not look.`,
    ``,
    `## 3. Engineering brief`,
    ``,
    `Before creating any knowledge, present your understanding with the three groups`,
    `separated. Never hide an assumption inside a conclusion.`,
    ``,
    `\`\`\``,
    `CONFIRMED   (the developer told you, or a source records it)`,
    `INFERRED    (you concluded it yourself)`,
    `UNKNOWN     (still open, and what it blocks)`,
    ``,
    `Component:   <component>`,
    `Change type: <new | extension | fix | refactor>`,
    `Affected:    <components>`,
    `Governed by: <ADR / rule / requirement ids found during discovery>`,
    `Impact:      <low | medium | high>`,
    `\`\`\``,
    ``,
    `Wait for confirmation. Only then write knowledge.`,
    ``,
    `## 4. Record the minimum`,
    ``,
    `Create the least knowledge that makes the work compilable:`,
    ``,
    `- prefer a **task** over a new requirement`,
    `- prefer a **requirement** over a new feature`,
    `- never duplicate knowledge that already exists`,
    ``,
    `Every task needs \`implements\` and \`touches\`: those relations are what makes context`,
    `compilable. Write the files into \`annona/\`, then \`annona check\`, then`,
    `\`annona compile\`. Fix what check reports.`,
    ``,
    `## 5. Plan`,
    ``,
    `Run \`annona context <task>\` and work from what it returns.`,
    ``,
    `If the verdict is \`MISSING_CONTEXT\`, stop. Report what \`missing\` names and ask. A`,
    `missing decision is a finding, not permission to improvise.`,
    ``,
    `Present a plan and wait for approval: affected components, steps, files you expect`,
    `to change, architectural impact, risks, and every assumption.`,
    ``,
    `**If implementation invalidates the plan, stop.** Update it, explain what changed,`,
    `and ask again. Silently diverging from an approved plan is worse than a slow plan.`,
    ``,
    `## 6. Implement`,
    ``,
    `Intent comes from the compiled context. Structure and precedent come from whatever`,
    `else you could reach. Use everything you have; none of it substitutes for another.`,
    ``,
    `Never invent requirements, architecture or rules. Missing knowledge is a finding,`,
    `not permission to improvise. If a rule blocks a sensible implementation, say so and`,
    `stop: that is the developer's decision.`,
    ``,
    `## 7. Review`,
    ``,
    `Iterative, no limit. Every pass checks two things, not one:`,
    ``,
    `**Does the implementation still satisfy the knowledge?** Requirements, ADRs and`,
    `rules from the compiled context. Cite the id you are checking against. Run the`,
    `project's tests. Report violations by id, never as an opinion about style.`,
    ``,
    `**Does the knowledge still describe the implementation?** If the code now does`,
    `something the graph does not record, that is drift. Record it or say so. Never`,
    `continue silently.`,
    ``,
    `Run \`annona doctor\` and report what it found about this task.`,
    ``,
    `## 8. Knowledge update`,
    ``,
    `When the work is accepted, ask exactly one question:`,
    ``,
    `> Did we learn anything that another engineer should know even if this code changes?`,
    ``,
    `Record only durable knowledge: a decision and why the alternatives were rejected, a`,
    `rule the team will keep, a requirement that was implicit, a capability that now`,
    `exists. **Never record what happened.** History belongs wherever this project keeps`,
    `its history, not in the knowledge graph.`,
    ``,
    `## 9. Done`,
    ``,
    `\`\`\``,
    `annona done <task> --touches=<components actually changed>`,
    `\`\`\``,
    ``,
    `That updates status and recompiles. Compile is infrastructure, not workflow: never`,
    `ask the developer to run it.`,
    ``,
    `## Rules of engagement`,
    ``,
    `- Exit codes: 0 success, 1 error, 2 usage, 3 halt. Code 3 means incomplete context.`,
    `- \`COMPLETE\` means the required kinds are present: requirement, feature, component.`,
    `  It does **not** mean the knowledge is sufficient. Rules and decisions can be`,
    `  entirely absent while the verdict still reads \`COMPLETE\`.`,
    `- The compiled context carries engineering knowledge only. Structure and history`,
    `  are yours to gather from whatever this environment provides.`,
    `- \`annona.yaml\` and \`annona/**\` are the source of truth. \`.annona/\` is generated and`,
    `  disposable. This file is generated: change the knowledge, not this file.`,
    `- If the workflow feels bureaucratic, say so. That is a product defect worth`,
    `  reporting, not something the developer should absorb.`,
  ];
  if (components.length > 0) {
    lines.push(`## Components`, ``);
    for (const c of components) lines.push(`- **${c.id}** ${c.title}${c.summary ? ` — ${c.summary}` : ''}`);
    lines.push(``);
  }
  if (rules.length > 0) {
    lines.push(`## Rules`, ``);
    for (const r of rules) lines.push(`- **${r.id}** ${r.title}${r.summary ? ` — ${r.summary}` : ''}`);
    lines.push(``);
  }
  if (terms.length > 0) {
    lines.push(`## Glossary`, ``);
    for (const t of terms) lines.push(`- **${t.title}** — ${t.summary ?? ''}`.trimEnd());
    lines.push(``);
  }

  lines.push(
    `## Commands you drive`, ``,
    `| Command | When |`,
    `|---|---|`,
    `| \`annona list <kind>\` | discovery |`,
    `| \`annona get <id>\` | discovery |`,
    `| \`annona context <task>\` | before planning and before implementing |`,
    `| \`annona check\` | after writing knowledge |`,
    `| \`annona compile\` | after writing knowledge |`,
    `| \`annona doctor\` | during review |`,
    `| \`annona done <task>\` | after the developer accepts |`,
    ``,
  );
  return lines.join('\n');
};
